package chains

import (
	"log/slog"

	"balancer/internal/routes"
)

// ProbeResult encapsulates the validation outcome of a blockchain health probe.
// Designed to be forward-compatible with block lag monitoring (Height and Timestamp).
type ProbeResult struct {
	Healthy   bool   // True if the endpoint responded with a valid, non-stale block status
	Height    uint64 // Block number or slot height (prepared for relative lag calculation)
	Timestamp int64  // Block production unix timestamp (prepared for head freshness verification)
}

// ChainDriver defines the contract for blockchain-specific probing and validation.
// Decouples network transport in server.HealthChecker from RPC protocol specifics.
type ChainDriver interface {
	Name() string                                          // Canonical chain identifier (e.g. "eth", "solana", "trx")
	ProbePayload() []byte                                  // Pre-allocated static JSON-RPC probe payload
	ParseResponse(statusCode int, body []byte) ProbeResult // Analyzes status code and parses response body
}

// registry holds drivers self-registered during package init() execution.
// Used solely at startup to decouple driver source files from generated chain IDs.
var registry = make(map[string]ChainDriver)

// Drivers provides O(1) zero-allocation lookup by numeric ChainID on the probe path.
var Drivers [routes.MaxChains]ChainDriver

// Register is invoked inside init() of each concrete chain file to add itself to the registry.
func Register(driver ChainDriver) {
	registry[driver.Name()] = driver
}

// InitDrivers maps self-registered chain drivers to their corresponding numeric ChainID
// generated by routes/generator.go. Executed once at application startup to populate
// the flat Drivers array, completely eliminating runtime hash lookups or mutexes.
func InitDrivers() {
	for chainID := range routes.MaxChains {
		name := routes.GetChainNameByID(int32(chainID))
		if driver, exists := registry[name]; exists {
			Drivers[chainID] = driver
			slog.Info("[Chains] Wired driver", "name", name, "chain_id", chainID)
		} else {
			slog.Warn("[Chains] No driver registered for chain", "name", name, "chain_id", chainID)
		}
	}
}
