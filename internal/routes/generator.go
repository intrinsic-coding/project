// generator.go
// Standalone code generator invoked during build (go generate / make generate).
// Parses config.json, normalizes endpoint URLs, sorts chain identities deterministically,
// and synthesizes internal/routes/loader_gen.go to bake static routing topologies directly into binary text.

//go:build ignore
// +build ignore

package main

import (
	"encoding/json"
	"fmt"
	"net/url"
	"os"
	"sort"
	"text/template"
)

type NodeConfig struct {
	Hostname string `json:"hostname"`
}

type ChainConfig struct {
	Nodes []NodeConfig `json:"nodes"`
}

type AppConfig struct {
	Chains map[string]ChainConfig `json:"chains"`
}

// tmpl defines the Go code template emitted into loader_gen.go.
// Bakes static manifests, route prefix lengths, and fast byte-prefix matching into the binary.
const tmpl = `// Code generated by routes/generator.go. DO NOT EDIT.
package routes

import (
	"bytes"
	"unsafe"
)

const (
{{- range $index, $chain := . }}
	Chain{{ $index }} = {{ $index }} /* {{ $chain.Name }} */
{{- end }}
	MaxChains = {{ len . }}
)

var ChainPrefixLens = [MaxChains]int{
	{{- range . }}
		len("/{{ .Name }}"),
	{{- end }}
}

type NodeRoute struct {
	Host   string
	Path   string
	SniPtr unsafe.Pointer
	SniLen int32
}

var StaticChainManifests = [][]NodeRoute{
{{- range . }}
	{
		{{- range .Nodes }}
		{Host: "{{ .Host }}", Path: "{{ .Path }}"},
		{{- end }}
	},
{{- end }}
}

func MatchChainID(path []byte) int {
{{- range . }}
	if bytes.HasPrefix(path, []byte("/{{ .Name }}")) {
		return Chain{{ .Index }}
	}
{{- end }}
	return -1
}

func GetChainNameByID(ChainID int32) string {
{{- range . }}
	if ChainID == {{ .Index }} {
		return "{{ .Name }}"
	}
{{- end }}
	return ""
}
`

type NodeData struct {
	Host string
	Path string
}

type ChainData struct {
	Index int
	Name  string
	Nodes []NodeData
}

func main() {
	file, err := os.ReadFile("config.json")
	if err != nil {
		panic(err)
	}
	var cfg AppConfig
	if err := json.Unmarshal(file, &cfg); err != nil {
		panic(err)
	}

	// Sort chain names lexicographically to ensure deterministic code generation across builds.
	var chainNames []string
	for name := range cfg.Chains {
		chainNames = append(chainNames, name)
	}
	sort.Strings(chainNames)

	var chains []ChainData
	for i, name := range chainNames {
		data := cfg.Chains[name]
		var nodes []NodeData
		for _, node := range data.Nodes {
			parsed, err := url.Parse(node.Hostname)
			host := node.Hostname
			path := ""
			if err == nil && parsed.Host != "" {
				host = parsed.Host
				path = parsed.Path
				if parsed.RawQuery != "" {
					path += "?" + parsed.RawQuery
				}
			}
			if path == "" {
				path = "/"
			}
			nodes = append(nodes, NodeData{
				Host: host,
				Path: path,
			})
		}
		chains = append(chains, ChainData{
			Index: i,
			Name:  name,
			Nodes: nodes,
		})
	}

	f, err := os.Create("internal/routes/loader_gen.go")
	if err != nil {
		panic(err)
	}
	defer f.Close()

	t := template.Must(template.New("r").Parse(tmpl))
	if err := t.Execute(f, chains); err != nil {
		panic(err)
	}
	fmt.Println("[Generator] internal/routes/loader_gen.go generated with strict order successfully!")
}
